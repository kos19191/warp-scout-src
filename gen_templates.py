#!/usr/bin/env python3
"""
Извлекает точные шаблоны мусорных пакетов (AWG I1/I2) из образцов конфигов генератора
и генерирует Kotlin-константы, чтобы приложение использовало байт-в-байт те же паттерны,
что и warp-generation.github.io.

Использование:
    python3 tools/gen_templates.py [путь-к-образцам ...]

По умолчанию читаются samples/*.conf (или, если их нет, ../uploads/WARPv*.txt).
"""
from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "core/src/main/kotlin/dev/warpscout/core/junk"

JUNK_RE = re.compile(r"^([IJSH]\d)\s*=\s*(.*)$", re.M)
CHUNK_RE = re.compile(r"<\s*b\s+0x([0-9a-fA-F]+)\s*>|<\s*r\s+(\d+)\s*>")


def junk_of(text: str) -> dict[str, list[tuple[str, object]]]:
    out: dict[str, list[tuple[str, object]]] = {}
    for name, value in JUNK_RE.findall(text):
        chunks = []
        for m in CHUNK_RE.finditer(value):
            chunks.append(("b", m.group(1)) if m.group(1) else ("r", int(m.group(2))))
        if chunks:
            out[name] = chunks
    return out


def wrap(hexstr: str, width: int = 96) -> str:
    parts = [hexstr[i:i + width] for i in range(0, len(hexstr), width)]
    return " +\n".join(f'        "{p}"' for p in parts)


def const(name: str, hexstr: str, comment: str) -> str:
    return (
        f"    /** {comment} (длина {len(hexstr) // 2} байт) */\n"
        f"    const val {name}: String =\n{wrap(hexstr)}\n"
    )


def main(argv: list[str]) -> int:
    files = [pathlib.Path(a) for a in argv[1:]] or sorted((ROOT / "samples").glob("*.conf"))
    if not files:
        print("не найдено образцов .conf — положите их в samples/", file=sys.stderr)
        return 1

    parsed = {f.name: junk_of(f.read_text()) for f in files}
    for name, junk in parsed.items():
        print(f"{name}: " + ", ".join(f"{k}={sum(len(v) * 2 if k2 == 'b' else int(v) for k2, v in lst)}B" for k, lst in junk.items()))

    def pick(file_hint: str, key: str, idx: int = 0, kind: str = "b"):
        for name, junk in parsed.items():
            if file_hint in name and key in junk:
                for typ, val in junk[key]:
                    if typ == kind and idx == 0:
                        return val
                    if typ == kind:
                        idx -= 1
        return None

    tls = pick("awg1", "I1")
    sip1 = pick("awg3", "I1")
    sip2 = pick("awg3", "I2")
    quic = pick("awg2", "I1")

    lines = [
        "// AUTO-GENERATED by tools/gen_templates.py — не редактируйте руками, правьте образцы и перегенерируйте.",
        "package dev.warpscout.core.junk",
        "",
        "/**",
        " * Точные байтовые шаблоны AWG-«шума» из конфигов генератора. Нужны, чтобы приложение",
        " * выдавало конфигурации, идентичные тем, что вы скачивали руками.",
        " */",
        "object JunkTemplates {",
    ]
    if tls:
        lines.append(const("TLS_FIXED_HEX", tls, "I1 — «AWG 2.0 / 1 вариант»"))
    if sip1:
        lines.append(const("SIP_I1_HEX", sip1, "I1 — SIP INVITE («3 вариант»)"))
    if sip2:
        lines.append(const("SIP_I2_HEX", sip2, "I2 — SIP 100 Trying («3 вариант»)"))
    if quic:
        lines.append(const("QUIC_SAMPLE_HEX", quic, "пример QUIC-маски («2 вариант»), на лету см. QuicMask"))
    lines.append("}")

    chunk_lines = [
        "// AUTO-GENERATED by tools/gen_templates.py",
        "package dev.warpscout.core.junk",
        "",
        "import dev.warpscout.core.crypto.Crypto",
        "import dev.warpscout.core.model.JunkChunk",
        "",
        "/** Те же шаблоны, но уже разложенные на чанки `<b …>` / `<r N>`. */",
        "object JunkTemplateChunks {",
        "    fun tlsFixed(): List<JunkChunk> = listOf(JunkChunk.Literal(Crypto.unHex(JunkTemplates.TLS_FIXED_HEX)))",
        "",
        "    fun sipI1(): List<JunkChunk> = listOf(JunkChunk.Literal(Crypto.unHex(JunkTemplates.SIP_I1_HEX)))",
        "",
        "    fun sipI2(): List<JunkChunk> = listOf(JunkChunk.Literal(Crypto.unHex(JunkTemplates.SIP_I2_HEX)))",
        "",
        "    fun quicSample(): List<JunkChunk> = listOf(JunkChunk.Literal(Crypto.unHex(JunkTemplates.QUIC_SAMPLE_HEX)))",
        "}",
    ]

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "JunkTemplates.kt").write_text("\n".join(lines) + "\n")
    (OUT_DIR / "JunkTemplateChunks.kt").write_text("\n".join(chunk_lines) + "\n")
    print("записано:", OUT_DIR / "JunkTemplates.kt")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
