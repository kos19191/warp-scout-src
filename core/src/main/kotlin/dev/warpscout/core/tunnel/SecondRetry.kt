package dev.warpscout.core.tunnel

/**
 * Повторы второго выхода после того, как все его серверы не ответили (с 1.10.50-beta1).
 *
 * Зачем. Журнал 26.11, 19:27–19:29: WARP на минуту замялся (rekey прошёл только с пятой инициации), и
 * все восемь серверов Proton один за другим «не ответили» — их рукопожатия шли через тот же WARP.
 * Второй выход сдался до следующего переподключения туннеля: 72 минуты ChatGPT, Claude, Gemini и Grok
 * ходили с российского адреса WARP, хотя при смене сети в 20:41 сервер ответил с первой инициации.
 * Теперь сервис пробует снова сам — через 1, 2, 5, 10 минут, дальше раз в 15 минут, а пока ждёт,
 * сайты второго выхода идут через WARP (TikTok — ждёт, через WARP не идёт).
 */
object SecondRetry {

    /** Пауза перед [n]-й повторной попыткой (n с 1). */
    fun delayMs(n: Int): Long = when {
        n <= 1 -> 60_000L
        n == 2 -> 120_000L
        n == 3 -> 300_000L
        n == 4 -> 600_000L
        else -> 900_000L
    }

    /** «1 мин», «15 мин» — для журнала. */
    fun text(ms: Long): String = "${(ms / 60_000L).coerceAtLeast(1L)} мин"
}
