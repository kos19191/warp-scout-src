package dev.warpscout.core.tune

/**
 * Подтвердилась ли сохранённая точка подбора.
 *
 * «Кандидат есть» — не подтверждение: победителем в отчёте становится любой кандидат, даже тот,
 * что не ответил ни разу. Принять такую точку за рабочую значило бы сэкономить минуты подбора и
 * получить конфиг, который не работает. Поэтому признаки настоящие: сервер ответил на handshake и,
 * если проверки изнутри туннеля шли, открылись сайты: при пяти и больше проверках — не меньше 75%
 * (с 1.10.49-beta2, как в версии для компьютера), при меньшем числе — хотя бы один.
 */
object CachedPoint {

    fun confirmed(
        replies: Int,
        resourcesTotal: Int,
        resourcesOk: Int,
        dataTried: Int = 0,
        dataReplies: Int = 0
    ): Boolean {
        if (replies <= 0) return false
        // Данные после рукопожатия проверяли, и ответа не было: такая точка не работает, сколько бы
        // она ни отвечала на рукопожатие (журнал 22.11: «вверх 5542, вниз 0»).
        if (dataTried > 0 && dataReplies <= 0) return false
        // Проверок изнутри не было (сборка без туннеля или они отключены) — судим по handshake.
        if (resourcesTotal <= 0) return true
        if (resourcesOk <= 0) return false
        // «Открылось хоть что-то» подтверждало и точку, уехавшую в российскую площадку (5 из 11 без
        // YouTube и Telegram), — и быстрый старт раз за разом не пускал подбор к другим подсетям.
        if (resourcesTotal >= MIN_FOR_SHARE && resourcesOk * 100 < resourcesTotal * MIN_SHARE_PCT) return false
        return true
    }

    /** С какого числа проверок изнутри требуется доля открывшихся [MIN_SHARE_PCT]. */
    const val MIN_FOR_SHARE = 5

    /** Сколько процентов сайтов должно открыться изнутри. */
    const val MIN_SHARE_PCT = 75
}
